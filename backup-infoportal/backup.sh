#!/usr/bin/env bash
# Nightly backup of info.altinn.no's Umbraco to storage outside Azure (Cloudflare R2).
#
#   1. Export the Azure SQL database to a .bacpac (sqlpackage, Entra token)
#   2. Encrypt it with age (public key only: this job can encrypt, never decrypt)
#   3. Upload it, plus a latest.json receipt, to DB_TARGET
#   4. Mirror the media container to MEDIA_TARGET (rclone sync, incremental)
#
# Targets are rclone paths, so the same script writes to R2 in the cluster and to a local folder
# when testing. Every failure makes the script exit non-zero, so the Kubernetes Job fails visibly.
#
# Configuration (environment variables):
#   ENV_NAME            at22 | at23 | tt02 | prod                                   (required)
#   SQL_SERVER          Azure SQL host, e.g. infop-at22-....database.windows.net     (required unless SKIP_DB=true)
#   SQL_DATABASE        default: umbraco
#   AGE_RECIPIENT       age public key (age1...) the backup is encrypted to          (required unless SKIP_DB=true)
#   DB_TARGET           rclone path for database backups, e.g. r2:infoportal-backup-at22/db
#   MEDIA_ACCOUNT       storage account with Umbraco media                          (required unless SKIP_MEDIA=true)
#   MEDIA_CONTAINER     default: umbraco
#   MEDIA_SOURCE_PREFIX folder in the container to mirror (default: media). The container also holds
#                       cache/ (ImageSharp, regenerated by Umbraco) and media-backup/, which are not needed.
#   MEDIA_TARGET        rclone path for the media mirror, e.g. r2:infoportal-snapshots-at22/media
#                       With the defaults, /media/abc/x.png on the site becomes media/abc/x.png in R2.
#   MEDIA_MAX_DELETE    stop instead of deleting more than this many mirrored files (default: 200)
#   SKIP_DB / SKIP_MEDIA  set to "true" to skip a part
#   EXPORT_TIMEOUT_SECONDS  abort the database export after this long (default: 1800)
#   WORK_DIR            scratch space for the bacpac (default: /tmp/backup). Needs room for ~2x the database.
#
# Authentication, in order of preference:
#   SQL:   SQL_ACCESS_TOKEN if set (local testing), otherwise Azure workload identity (in AKS)
#   Media: MEDIA_SAS_URL if set (local testing), otherwise Azure workload identity (rclone env_auth)
#   R2:    rclone remote "r2" from RCLONE_CONFIG_R2_* variables (see README)
#
# Tokens and SAS URLs are never logged.

set -Eeuo pipefail

log() { printf '%s [backup-infoportal] %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*" >&2; }
die() { log "ERROR: $*"; exit 1; }
is_true() { [ "${1:-}" = "true" ]; }

ENV_NAME="${ENV_NAME:-}"
SQL_DATABASE="${SQL_DATABASE:-umbraco}"
MEDIA_CONTAINER="${MEDIA_CONTAINER:-umbraco}"
MEDIA_SOURCE_PREFIX="${MEDIA_SOURCE_PREFIX-media}"
MEDIA_MAX_DELETE="${MEDIA_MAX_DELETE:-200}"
WORK_DIR="${WORK_DIR:-/tmp/backup}"
RCLONE_FLAGS=(--stats=60s --stats-one-line --stats-log-level NOTICE)

[ -n "$ENV_NAME" ] || die "ENV_NAME is required"

# --- authentication ---------------------------------------------------------------------------

# Exchanges the projected Kubernetes service account token for an Entra access token.
# The workload identity webhook injects AZURE_CLIENT_ID, AZURE_TENANT_ID, AZURE_AUTHORITY_HOST
# and AZURE_FEDERATED_TOKEN_FILE into pods that use a service account with workload identity.
workload_identity_token() {
	local scope="$1"
	[ -n "${AZURE_FEDERATED_TOKEN_FILE:-}" ] || die "no SQL_ACCESS_TOKEN and no workload identity (AZURE_FEDERATED_TOKEN_FILE) available"

	curl -fsS -X POST "${AZURE_AUTHORITY_HOST%/}/${AZURE_TENANT_ID}/oauth2/v2.0/token" \
		--data-urlencode "client_id=${AZURE_CLIENT_ID}" \
		--data-urlencode "scope=${scope}" \
		--data-urlencode "grant_type=client_credentials" \
		--data-urlencode "client_assertion_type=urn:ietf:params:oauth:client-assertion-type:jwt-bearer" \
		--data-urlencode "client_assertion=$(cat "$AZURE_FEDERATED_TOKEN_FILE")" |
		jq -er '.access_token' || die "could not get an Entra token for ${scope}"
}

sql_token() {
	if [ -n "${SQL_ACCESS_TOKEN:-}" ]; then
		printf '%s' "$SQL_ACCESS_TOKEN"
	else
		workload_identity_token "https://database.windows.net/.default"
	fi
}

configure_media_remote() {
	export RCLONE_CONFIG_AZ_TYPE=azureblob
	if [ -n "${MEDIA_SAS_URL:-}" ]; then
		export RCLONE_CONFIG_AZ_SAS_URL="$MEDIA_SAS_URL"
	else
		# env_auth uses the Azure SDK's default credential chain, which picks up workload identity.
		export RCLONE_CONFIG_AZ_ACCOUNT="$MEDIA_ACCOUNT"
		export RCLONE_CONFIG_AZ_ENV_AUTH=true
	fi
}

# --- steps ------------------------------------------------------------------------------------

backup_database() {
	: "${SQL_SERVER:?SQL_SERVER is required}"
	: "${AGE_RECIPIENT:?AGE_RECIPIENT is required}"
	: "${DB_TARGET:?DB_TARGET is required}"

	local started stamp bacpac encrypted token
	started=$(date +%s)
	stamp=$(date -u +%Y-%m-%dT%H-%M-%SZ)
	bacpac="${WORK_DIR}/${SQL_DATABASE}-${ENV_NAME}-${stamp}.bacpac"
	encrypted="${bacpac}.age"

	# sqlpackage retries an unreachable server for over 10 minutes. Fail fast instead.
	timeout 15 bash -c "</dev/tcp/${SQL_SERVER}/1433" 2>/dev/null || die "cannot reach ${SQL_SERVER}:1433 (DNS, Private Link or firewall)"

	# Azure SQL's certificate is issued for *.database.windows.net. When the server is addressed by its
	# privatelink name (as in scripts/db/environments.conf), tell the client which name to validate,
	# instead of turning certificate validation off.
	local cert_host="${SQL_SERVER/.privatelink./.}"
	local conn="Server=tcp:${SQL_SERVER},1433;Initial Catalog=${SQL_DATABASE};Encrypt=True;TrustServerCertificate=False;HostNameInCertificate=${cert_host};Connection Timeout=30"

	log "exporting ${SQL_DATABASE} on ${SQL_SERVER}"
	token=$(sql_token)
	# A token lasts about an hour, which is far more than this database needs.
	# sqlpackage can wait forever on a connection that silently died, so cap the whole export.
	timeout --kill-after=30s "${EXPORT_TIMEOUT_SECONDS:-1800}" sqlpackage /Action:Export \
		/SourceConnectionString:"$conn" \
		/AccessToken:"$token" \
		/TargetFile:"$bacpac" \
		/Quiet:True >&2 || die "sqlpackage export failed or timed out (exit $?)"
	unset token

	local plain_sha plain_size
	plain_sha=$(sha256sum "$bacpac" | cut -d' ' -f1)
	plain_size=$(stat -c %s "$bacpac")

	log "encrypting ($(numfmt --to=iec "$plain_size"))"
	age --encrypt --recipient "$AGE_RECIPIENT" --output "$encrypted" "$bacpac" || die "age encryption failed"
	# The unencrypted copy never leaves the pod, and does not stay on disk longer than needed.
	rm -f "$bacpac"

	local encrypted_sha encrypted_size object
	encrypted_sha=$(sha256sum "$encrypted" | cut -d' ' -f1)
	encrypted_size=$(stat -c %s "$encrypted")
	object="$(basename "$encrypted")"

	log "uploading ${object} to ${DB_TARGET}"
	rclone copyto "$encrypted" "${DB_TARGET%/}/${object}" "${RCLONE_FLAGS[@]}" || die "upload of database backup failed"
	rm -f "$encrypted"

	jq -n \
		--arg env "$ENV_NAME" \
		--arg object "$object" \
		--arg createdAt "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
		--arg database "$SQL_DATABASE" \
		--arg server "$SQL_SERVER" \
		--arg plainSha "$plain_sha" \
		--arg encryptedSha "$encrypted_sha" \
		--argjson plainSize "$plain_size" \
		--argjson encryptedSize "$encrypted_size" \
		--argjson seconds "$(($(date +%s) - started))" \
		'{env: $env, object: $object, createdAt: $createdAt, database: $database, server: $server,
		  bacpac: {bytes: $plainSize, sha256: $plainSha},
		  encrypted: {bytes: $encryptedSize, sha256: $encryptedSha},
		  durationSeconds: $seconds}' |
		rclone rcat "${DB_TARGET%/}/latest.json" || die "could not write latest.json"

	log "database backup done: ${object}"
}

mirror_media() {
	: "${MEDIA_TARGET:?MEDIA_TARGET is required}"
	[ -n "${MEDIA_SAS_URL:-}" ] || : "${MEDIA_ACCOUNT:?MEDIA_ACCOUNT is required}"

	configure_media_remote
	local source="az:${MEDIA_CONTAINER}${MEDIA_SOURCE_PREFIX:+/${MEDIA_SOURCE_PREFIX}}"
	log "mirroring ${source#az:} to ${MEDIA_TARGET}"
	# sync also deletes files that were deleted in Umbraco. --max-delete stops the run instead of
	# emptying the mirror if the source ever looks unexpectedly empty.
	rclone sync "$source" "$MEDIA_TARGET" \
		--fast-list \
		--max-delete "$MEDIA_MAX_DELETE" \
		"${RCLONE_FLAGS[@]}" || die "media mirror failed"

	log "media mirror done"
}

# --- main -------------------------------------------------------------------------------------

cleanup() { rm -rf "$WORK_DIR"; }
trap cleanup EXIT
mkdir -p "$WORK_DIR"
chmod 700 "$WORK_DIR"

# Runs a step in a subshell with errexit active, and records it as failed instead of stopping,
# so a media problem does not prevent the database backup (or the other way round).
# (Calling it as `(step) || ...` would silently disable errexit inside the step.)
run_step() {
	local name="$1" status
	set +e
	(
		set -e
		"$name"
	)
	status=$?
	set -e
	[ "$status" -eq 0 ] || failed+=("$name")
}

log "starting backup for ${ENV_NAME}"
failed=()

if is_true "${SKIP_DB:-}"; then
	log "SKIP_DB=true, skipping database"
else
	run_step backup_database
fi

if is_true "${SKIP_MEDIA:-}"; then
	log "SKIP_MEDIA=true, skipping media"
else
	run_step mirror_media
fi

if [ ${#failed[@]} -gt 0 ]; then
	die "backup finished with failures: ${failed[*]}"
fi
log "backup finished successfully"
